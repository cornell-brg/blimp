task run_fp_div_test_cases();

  // 4.0 / 2.0 = 2.0
  send( 32'h0, 0, 32'h40800000, 32'h40000000, 5'd1, OP_FADD_S );
  recv( 32'h0, 0, 5'd1, 32'h40000000, 1'b1 );

  // 1.0 / 2.0 = 0.5
  send( 32'h0, 1, 32'h3F800000, 32'h40000000, 5'd2, OP_FADD_S );
  recv( 32'h0, 1, 5'd2, 32'h3F000000, 1'b1 );

  // -4.0 / 2.0 = -2.0
  send( 32'h0, 2, 32'hC0800000, 32'h40000000, 5'd3, OP_FADD_S );
  recv( 32'h0, 2, 5'd3, 32'hC0000000, 1'b1 );

  // 0.0 / 0.0 = NaN
  send( 32'h0, 3, 32'h00000000, 32'h00000000, 5'd4, OP_FADD_S );
  recv( 32'h0, 3, 5'd4, 32'h7FC00000, 1'b1 );

  // 1.0 / 0.0 = +Inf
  send( 32'h0, 4, 32'h3F800000, 32'h00000000, 5'd5, OP_FADD_S );
  recv( 32'h0, 4, 5'd5, 32'h7F800000, 1'b1 );

  // -1.0 / 0.0 = -Inf
  send( 32'h0, 5, 32'hBF800000, 32'h00000000, 5'd6, OP_FADD_S );
  recv( 32'h0, 5, 5'd6, 32'hFF800000, 1'b1 );

  // Inf / Inf = NaN
  send( 32'h0, 6, 32'h7F800000, 32'h7F800000, 5'd7, OP_FADD_S );
  recv( 32'h0, 6, 5'd7, 32'h7FC00000, 1'b1 );

    // Inf / 1.0 = Inf
  send( 32'h0, 7, 32'h7F800000, 32'h3F800000, 5'd8, OP_FADD_S );
  recv( 32'h0, 7, 5'd8, 32'h7F800000, 1'b1 );

  // 1.0 / Inf = 0.0
  send( 32'h0, 0, 32'h3F800000, 32'h7F800000, 5'd9, OP_FADD_S );
  recv( 32'h0, 0, 5'd9, 32'h00000000, 1'b1 );

  // 0.0 / 1.0 = 0.0
  send( 32'h0, 1, 32'h00000000, 32'h3F800000, 5'd10, OP_FADD_S );
  recv( 32'h0, 1, 5'd10, 32'h00000000, 1'b1 );
  
endtask